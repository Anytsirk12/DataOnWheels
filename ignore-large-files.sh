#!/bin/sh
# Rebuilds the "Over 100 MB" block in .gitignore from the files that are currently over GitHub's 100 MB limit, and unstages any of them that were already added.
# Git can't ignore files by size on its own, so this runs as a pre-commit hook (see .git/hooks/pre-commit) and can also be run by hand: sh ignore-large-files.sh
# 11.5.26 KF: first version.

cd "$(git rev-parse --show-toplevel)" || exit 1

START="# >>> Over 100 MB (auto-generated by ignore-large-files.sh, don't edit by hand)"
END="# <<< Over 100 MB"

LIST=$(find . -path ./.git -prune -o -type f -size +100M -print | sed 's|^\./|/|' | sort)

# Keep everything outside the managed block, then append a fresh block.
touch .gitignore
awk -v s="$START" -v e="$END" '$0==s{skip=1;next} $0==e{skip=0;next} !skip' .gitignore > .gitignore.tmp
{
  cat .gitignore.tmp
  echo "$START"
  [ -n "$LIST" ] && echo "$LIST"
  echo "$END"
} > .gitignore
rm -f .gitignore.tmp

# Unstage any large file that was already added, so the commit can't include it.
echo "$LIST" | while IFS= read -r f; do
  [ -z "$f" ] && continue
  p="${f#/}"
  if git ls-files --error-unmatch -- "$p" >/dev/null 2>&1; then
    git rm --cached --quiet -- "$p" && echo "ignore-large-files: removed $p from the index (over 100 MB)"
  fi
done

git add .gitignore
exit 0
